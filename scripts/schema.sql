CREATE TABLE IF NOT EXISTS users (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR(255) NOT NULL UNIQUE,
    role VARCHAR(255) NOT NULL,
    is_available BOOLEAN NOT NULL,
    max_concurrent_tickets INTEGER NOT NULL,
    created_at TIMESTAMPTZ NOT NULL
);

CREATE TABLE IF NOT EXISTS customers (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(255) NOT NULL,
    email VARCHAR(255) NOT NULL,
    tier VARCHAR(255) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL
);

CREATE TABLE IF NOT EXISTS skills (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(255) NOT NULL UNIQUE
);

CREATE TABLE IF NOT EXISTS user_skills (
    user_id INTEGER NOT NULL REFERENCES users(id),
    skill_id INTEGER NOT NULL REFERENCES skills(id),
    proficiency_level INTEGER NOT NULL,
    PRIMARY KEY (user_id, skill_id)
);

CREATE TABLE IF NOT EXISTS tickets (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ticket_number VARCHAR(255) NOT NULL UNIQUE,
    customer_id INTEGER NOT NULL REFERENCES customers(id),
    assigned_agent_id INTEGER REFERENCES users(id),
    required_skill_id INTEGER REFERENCES skills(id),
    sla_policy_key VARCHAR(255),
    sla_policy_version VARCHAR(255),
    calendar_config_version VARCHAR(255),
    subject VARCHAR(255) NOT NULL,
    description TEXT,
    urgency VARCHAR(255),
    priority VARCHAR(255),
    is_priority_overridden BOOLEAN,
    status VARCHAR(255),
    sla_clock_status VARCHAR(255),
    sla_target_seconds INTEGER,
    sla_escalation_threshold_pct INTEGER,
    sla_consumed_seconds INTEGER,
    sla_last_started_at TIMESTAMPTZ,
    sla_deadline_at TIMESTAMPTZ,
    sla_breached BOOLEAN,
    risk_score INTEGER,
    risk_level VARCHAR(255),
    reopened_count INTEGER,
    reassignment_count INTEGER,
    first_assigned_at TIMESTAMPTZ,
    resolved_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL,
    updated_at TIMESTAMPTZ NOT NULL
);

CREATE TABLE IF NOT EXISTS ticket_assignments (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ticket_id INTEGER NOT NULL REFERENCES tickets(id),
    agent_id INTEGER NOT NULL REFERENCES users(id),
    assigned_by INTEGER NOT NULL REFERENCES users(id),
    assignment_type VARCHAR(255),
    routing_score NUMERIC,
    routing_factors JSONB,
    assigned_at TIMESTAMP,
    ended_at TIMESTAMP,
    assignment_duration_business_seconds INTEGER
);

CREATE TABLE IF NOT EXISTS ticket_pauses (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ticket_id INTEGER NOT NULL REFERENCES tickets(id),
    initiated_by INTEGER NOT NULL REFERENCES users(id),
    attempted_reason VARCHAR(255),
    decision_status VARCHAR(255),
    approved_by INTEGER REFERENCES users(id),
    remarks TEXT,
    requested_at TIMESTAMPTZ,
    paused_at TIMESTAMPTZ,
    resumed_at TIMESTAMPTZ,
    paused_duration_business_seconds INTEGER
);

CREATE TABLE IF NOT EXISTS ticket_escalations (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ticket_id INTEGER NOT NULL REFERENCES tickets(id),
    created_by INTEGER NOT NULL REFERENCES users(id),
    owner_supervisor_id INTEGER REFERENCES users(id),
    assigned_agent_id INTEGER REFERENCES users(id),
    reason VARCHAR(255),
    description TEXT,
    status VARCHAR(255),
    created_at TIMESTAMPTZ,
    claimed_at TIMESTAMPTZ,
    resolved_at TIMESTAMPTZ,
    resolution_notes TEXT
);

CREATE TABLE IF NOT EXISTS ticket_events (
    id UUID PRIMARY KEY,
    ticket_id INTEGER NOT NULL REFERENCES tickets(id),
    actor_id INTEGER REFERENCES users(id),
    actor_type VARCHAR(255),
    event_type VARCHAR(255),
    event_version INTEGER NOT NULL,
    from_state VARCHAR(255),
    to_state VARCHAR(255),
    sla_consumed_seconds_snapshot INTEGER,
    risk_score_snapshot INTEGER,
    metadata JSONB,
    created_at TIMESTAMPTZ
);
